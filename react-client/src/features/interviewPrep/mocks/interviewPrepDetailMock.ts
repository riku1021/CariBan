export function getInterviewPrepDetail(prepId: string): InterviewPrepDetail | null {
  const cached = detailById[prepId];
  if (cached) {
    return cached;
  }
  const item = interviewPrepsMock.find((prep) => prep.id === prepId);
  if (!item) {
    return null;
  }
  return buildDetailFromItem(item);
}
